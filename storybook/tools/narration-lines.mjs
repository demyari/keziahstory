// Collects the character sentences worth pre-recording with Kokoro: each
// friend's own hello/tap/cheer lines plus fixed sentences that friends say
// in many stories. Writes a render list for render.py and the clip manifest
// (js/audio/clip-manifest.js is generated from it by --manifest).
//
// Usage:
//   node tools/narration-lines.mjs list out.json     -> items for render.py
//   node tools/narration-lines.mjs manifest clipsDir -> writes js/audio/clips.js

import fs from 'node:fs';
import path from 'node:path';
import { CHARACTERS } from '../js/content/characters.js';
import { clipId, splitSentences } from '../js/audio/clipid.js';
import { playOne } from './simulate.mjs';
import { LETTERS } from '../js/content/alphabet.js';

// Kokoro voice for each friend (speed tuned per personality).
export const CLIP_VOICES = {
  sparkle: ['bf_lily', 1.0], hoot: ['bm_george', 0.88], rosie: ['af_sky', 1.05], bramble: ['am_santa', 0.88],
  pip: ['am_puck', 1.05], coral: ['af_bella', 1.0], shelly: ['bf_isabella', 0.85], ember: ['af_nicole', 0.95],
  dotty: ['bf_alice', 0.88], flutter: ['af_nova', 0.95], benny: ['am_echo', 1.08], pebble: ['af_river', 1.0],
  buzz: ['af_aoede', 1.08], wobble: ['am_onyx', 0.85], snip: ['am_eric', 1.08], ribbit: ['am_liam', 1.05],
};

function collect() {
  const want = new Map(); // id -> {who,text}
  const add = (who, text) => {
    const id = clipId(who, text);
    if (!want.has(id)) want.set(id, { id, who, text });
  };
  for (const [id, c] of Object.entries(CHARACTERS)) {
    for (const line of [...c.hello, ...c.taps, ...c.cheer]) for (const s of splitSentences(line)) add(id, s);
  }
  // fixed sentences shared by many friends
  const speakers = new Map();
  for (let i = 0; i < 30000; i++) {
    const { pages } = playOne(`CLIP-${i}`, i, { learn: { countMin: 2, countMax: 10, letters: [LETTERS[i % 26], 'A', 'B'], numerals: true } });
    for (const p of pages) for (const l of [...p.lines, ...p.after]) {
      if (l.who === 'n') continue;
      for (const s of splitSentences(l.text)) {
        if (!speakers.has(s)) speakers.set(s, new Set());
        speakers.get(s).add(l.who);
      }
    }
  }
  const names = Object.values(CHARACTERS).map((c) => c.name);
  for (const [s, who] of speakers) {
    if (who.size < 3) continue;
    if (names.some((nm) => s.includes(nm))) continue;
    if (/\b[A-Z]\b(?!')/.test(s.replace(/^I /, '')) || /\b(one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|thirteen|fourteen|fifteen|sixteen|seventeen|eighteen|nineteen|twenty)\b/i.test(s)) continue;
    if (speakers.get(s).size < 3) continue;
    for (const w of who) add(w, s);
  }
  return [...want.values()];
}

const [mode, arg] = process.argv.slice(2);
if (mode === 'list') {
  const items = collect().map((x) => ({ id: x.id, text: x.text, voice: CLIP_VOICES[x.who][0], speed: CLIP_VOICES[x.who][1] }));
  fs.writeFileSync(arg, JSON.stringify(items, null, 0));
  console.log(`${items.length} clips listed`);
} else if (mode === 'manifest') {
  const have = new Set(fs.readdirSync(arg).filter((f) => f.endsWith('.ogg')).map((f) => f.slice(0, -4)));
  const ids = collect().map((x) => x.id).filter((id) => have.has(id)).sort();
  const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../js/audio/clips.js');
  fs.writeFileSync(out, `// Generated by tools/narration-lines.mjs. Pre-recorded character clips (Kokoro-82M, Apache-2.0).\nexport const CLIPS = new Set(${JSON.stringify(ids)});\n`);
  console.log(`${ids.length} clips in manifest`);
}
